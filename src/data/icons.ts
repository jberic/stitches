export function iconCells(name: IconName, size: IconSize): { width: number; height: number; cells: Uint8Array } {
  const rows = ICONS[name][size]
  const cells = new Uint8Array(rows.join('').split('').map((c) => (c === '#' ? 1 : 0)))
  return { width: rows[0].length, height: rows.length, cells }
}
